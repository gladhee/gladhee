// Classify tracked files locally. The JSON stream never leaves the machine.
package main

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"regexp"
	"strings"

	enry "github.com/go-enry/go-enry/v2"
)

var generatedHeader = regexp.MustCompile("(?im)^[ \\t]*(?://|/\\*+|\\*|#|--)[ \\t]*(?:(?:this (?:file|code|script) (?:is|was) )?(?:auto[- ]?generated|automatically generated|generated by)|code generated|@generated|do not edit)\\b")
var insertStart = regexp.MustCompile("(?im)^[ \\t]*insert[ \\t]+into\\b")
var literalInsert = regexp.MustCompile("(?im)^[ \\t]*insert[ \\t]+into\\s+[^;]{0,1000}?\\bvalues\\s*\\(")
var sqlLogic = regexp.MustCompile("(?im)^[ \\t]*(?:create\\s+(?:or\\s+replace\\s+)?(?:function|procedure|trigger|view|policy|table)|alter\\s+table|with\\s+recursive|delete\\s+from)\\b")

func generatedOrData(r request) bool {
	first := r.Content
	if len(first) > 4096 {
		first = first[:4096]
	}
	if generatedHeader.Match(first) {
		return true
	}
	if !strings.HasSuffix(strings.ToLower(r.Path), ".sql") {
		return false
	}
	if bytes.Contains(bytes.ToLower(first), []byte("postgresql database dump")) {
		return true
	}
	inserts := len(insertStart.FindAllIndex(r.Content, -1))
	return inserts >= 25 && !sqlLogic.Match(r.Content) && len(literalInsert.FindAllIndex(r.Content, -1)) == inserts
}

type request struct {
	Path       string
	Content    []byte
	Probe      bool
	Executable bool
	Graphics   bool
	Override   string
	Detectable bool
}

func eligible(lang string) bool {
	if lang == "Roff" || lang == "Roff Manpage" {
		return false
	}
	kind := enry.GetLanguageType(lang)
	return kind == enry.Programming || kind == enry.Markup || lang == "SQL" || lang == "PLpgSQL"
}

func classify(r request) string {
	if (enry.IsVendor(r.Path) && !r.Graphics) || enry.IsDocumentation(r.Path) {
		return ""
	}
	if r.Probe {
		if r.Executable || r.Override != "" || r.Detectable {
			return "candidate"
		}
		if lang, _ := enry.GetLanguageByFilename(r.Path); eligible(lang) {
			return "candidate"
		}
		for _, lang := range enry.GetLanguagesByExtension(r.Path, nil, nil) {
			if eligible(lang) {
				return "candidate"
			}
		}
		return ""
	}
	if enry.IsBinary(r.Content) || enry.IsGenerated(r.Path, r.Content) || generatedOrData(r) {
		return ""
	}
	lang := r.Override
	if lang == "" {
		lang = enry.GetLanguage(r.Path, r.Content)
	}
	if lang == "" || (!r.Detectable && !eligible(lang)) {
		return ""
	}
	if group := enry.GetLanguageGroup(lang); group != "" {
		return group
	}
	return lang
}

func main() {
	decoder := json.NewDecoder(bufio.NewReader(os.Stdin))
	writer := bufio.NewWriter(os.Stdout)
	defer writer.Flush()
	for {
		var r request
		if err := decoder.Decode(&r); err != nil {
			if err == io.EOF {
				break
			}
			fmt.Fprintln(os.Stderr, "Invalid classification request.")
			os.Exit(1)
		}
		lang := classify(r)
		fmt.Fprintln(writer, strings.Join([]string{lang, enry.GetColor(lang)}, "\t"))
	}
}
